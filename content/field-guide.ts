const photo = (
  file: string,
  width: number,
  height: number,
  alt: string,
  author: string,
  license: string,
  source: string,
): GuidePhoto => ({ src: `/media/field-guide/${file}.jpg`, width, height, alt, credit: { author, license, source } });

const own = (asset: { src: unknown; width: number; height: number; alt: string }): GuidePhoto => ({
  src: String(asset.src),
  width: asset.width,
  height: asset.height,
  alt: asset.alt,
  credit: { author: "Tanzin Tsewang" },
});

/** Inclusive month range that may wrap the year, e.g. range(11, 3) → Nov–Mar. */
const range = (from: number, to: number) => {
  const months: number[] = [];
  for (let m = from; ; m = (m % 12) + 1) {
    months.push(m);
    if (m === to) return months;
  }
};
const allYear = range(1, 12);

